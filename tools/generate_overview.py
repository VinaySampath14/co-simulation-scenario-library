"""Generate the Level 1 overview from the existing catalogue records."""

import re

if __package__:
    from .validate import ROOT, validate_catalogue
else:
    from validate import ROOT, validate_catalogue


def cell(text):
    return " ".join(text.split()).replace("|", r"\|")


def source_link(source, folder):
    if source["type"] == "source_archive":
        return f"[Archive checksum]({folder}/scenario.yaml)"
    url = source["url"]
    label = cell(source["title"])
    revision = source.get("version_or_commit") or ""
    if source["type"] == "source_repository" and re.fullmatch(r"[a-f0-9]{40,64}", revision):
        label += f" (`{revision[:8]}`)"
        if url.startswith("https://github.com/"):
            url = f"{url.removesuffix('.git')}/tree/{revision}"
        elif url.startswith("https://gitlab.com/"):
            url = f"{url.removesuffix('.git')}/-/tree/{revision}"
    return f"[{label}]({url})"


def generate_overview(documents, records):
    lines = [
        "# Level 1 scenario overview", "",
        "<!-- Generated by python tools/generate_overview.py. Edit the scenario records to update this table. -->",
        "",
        "The table summarizes the scenarios in the library. Follow a title for its full description, "
        "or open the [evidence register](../evidence/evidence.yaml) for original source locators and revisions. "
        "Component names and roles are shown as recorded for each scenario.",
        "",
        "| Scenario | Domain | Components and roles | Short description | Original sources |",
        "| --- | --- | --- | --- | --- |",
    ]
    for identifier in sorted(key for key in records if key.startswith("SCN-")):
        scenario = records[identifier]
        folder = f"../scenarios/{identifier}"
        title = f"[`{identifier}` {cell(scenario['title'])}]({folder}/description.md)"
        domain = cell(", ".join(tag.replace("_", " ") for tag in scenario["domain"]))
        participations = documents.get(f"scenarios/{identifier}/participations.yaml", {})
        components = "<br>".join(dict.fromkeys(
            cell(f"{entry['reported_component']} ({entry['role'].replace('_', ' ')})")
            if entry.get("role") else cell(entry["reported_component"])
            for entry in participations.get("participations", [])
        )) or "Unresolved"
        summary = cell(scenario.get("technical_purpose") or scenario.get("research_objective") or "Unresolved")
        if summary[-1] not in ".!?":
            summary += "."
        sources = [
            source_link(records[key], folder)
            for key in scenario["source_ids"]
            if records[key]["type"] != "package_release"
        ]
        lines.append(f"| {title} | {domain} | {components} | {summary} | {'<br>'.join(sources)} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    output = ROOT / "catalogue/overview.md"
    output.write_text(generate_overview(*validate_catalogue()), encoding="utf-8", newline="\n")
    print(f"Wrote {output.relative_to(ROOT)}")
